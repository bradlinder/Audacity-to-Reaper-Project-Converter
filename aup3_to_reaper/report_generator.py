"""Migration report generator (.md).

Summarizes converted project metrics, lists unmapped features, and provides
actionable manual adjustment recommendations for REAPER users.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any, Dict, List

from .models import AudacityProject

logger = logging.getLogger(__name__)


class ReportGenerator:
    """Generates comprehensive Markdown migration report."""

    def __init__(self, project: AudacityProject, output_dir: Path) -> None:
        self.project = project
        self.output_dir = Path(output_dir).resolve()

    def generate(self, extraction_summary: Dict[str, Any]) -> str:
        """Construct the Markdown report text."""
        p = self.project
        lines: List[str] = [
            f"# Audacity to REAPER Migration Report: `{p.name}`",
            "",
            "> **Generated by `aup3-to-reaper`**  ",
            "> Standalone & Offline Audacity to REAPER Conversion Tool",
            "",
            "## 1. Project Overview",
            "",
            "| Metric | Value |",
            "| :--- | :--- |",
            f"| **Source File** | `{p.project_path.name}` |",
            f"| **Source Full Path** | `{p.project_path}` |",
            f"| **Output Directory** | `{self.output_dir}` |",
            f"| **Project Sample Rate** | {int(p.sample_rate):,} Hz |",
            f"| **Audacity Version** | {p.audacity_version or '3.x'} |",
            f"| **Total Tracks** | {len(p.tracks)} |",
            f"| **Total Audio Clips / Items** | {p.total_clips} |",
            f"| **Extracted Audio Files** | {extraction_summary.get('total_files', 0)} files ({extraction_summary.get('total_bytes', 0) / (1024*1024):.2f} MB) |",
            f"| **Total Audio Duration** | {p.total_duration:.2f} seconds ({p.total_duration / 60.0:.2f} minutes) |",
            f"| **Timeline Markers** | {len(p.markers)} |",
            f"| **Timeline Regions** | {len(p.regions)} |",
            "",
            "---",
            "",
            "## 2. Track & Media Manifest",
            "",
            "| # | Track Name | Channel Layout | Volume (dB) | Pan | Mute/Solo | Clips | Realtime Effects |",
            "| :-: | :--- | :--- | :-: | :-: | :-: | :-: | :--- |",
        ]

        for tr in p.tracks:
            # Linear gain to dB
            import math
            gain_db = 20.0 * math.log10(tr.gain) if tr.gain > 0.00001 else -144.0
            pan_str = "Center" if abs(tr.pan) < 0.01 else (f"{int(abs(tr.pan)*100)}% L" if tr.pan < 0 else f"{int(tr.pan*100)}% R")
            ms_str = []
            if tr.mute:
                ms_str.append("Mute")
            if tr.solo:
                ms_str.append("Solo")
            ms_display = "/".join(ms_str) if ms_str else "Normal"
            ch_str = "Right" if tr.channel == 1 else ("Left (Linked)" if tr.linked else "Mono / Stereo")
            eff_names = ", ".join(e.clean_name() for e in tr.effects) if tr.effects else "None"

            lines.append(
                f"| {tr.track_id} | **{tr.name}** | {ch_str} | {gain_db:+.1f} dB | {pan_str} | {ms_display} | {len(tr.clips)} | {eff_names} |"
            )

        lines.extend([
            "",
            "### Extracted Audio Clips",
            "",
            "| Track | Clip Name | Output File | Offset | Timeline Duration | Stretch Ratio |",
            "| :--- | :--- | :--- | :-: | :-: | :-: |",
        ])

        for tr in p.tracks:
            for cl in tr.clips:
                fname = cl.extracted_filename or "N/A"
                lines.append(
                    f"| {tr.name} | {cl.name} | `{fname}` | {cl.timeline_offset:.3f} s | {cl.timeline_duration:.3f} s | {cl.stretch_ratio:.2f}x |"
                )

        # Effects translation section
        effects_count = sum(len(t.effects) for t in p.tracks)
        lines.extend([
            "",
            "---",
            "",
            "## 3. Realtime Effects Translation",
            "",
        ])

        if effects_count == 0:
            lines.append("No non-destructive realtime effect chains were active in this Audacity project.")
        else:
            lines.extend([
                f"Detected **{effects_count}** realtime track effect(s).",
                "",
                "| Track | Audacity Effect ID | Target REAPER Plugin | Active | Mapped Parameters |",
                "| :--- | :--- | :--- | :-: | :--- |",
            ])
            from .fx_mapper import FXMapper
            mapper = FXMapper(p)
            for tr in p.tracks:
                for eff in tr.effects:
                    target_plugin, _, params = mapper.classify_effect(eff)
                    p_str = ", ".join(f"{k}={v}" for k, v in list(params.items())[:4]) or "Default"
                    lines.append(
                        f"| {tr.name} | `{eff.clean_name()}` | `{target_plugin}` | {'Yes' if eff.active else 'Bypassed'} | {p_str} |"
                    )

            lines.extend([
                "",
                "> [!TIP]",
                "> To automatically instantiate and configure all plugin chains above, run the companion script `session_load_fx.lua` inside REAPER via **Actions -> Load ReaScript**.",
            ])

        # Timeline Cues
        if p.markers or p.regions:
            lines.extend([
                "",
                "---",
                "",
                "## 4. Timeline Cues (Markers & Regions)",
                "",
                "| Type | ID | Position / Start | End Position | Name / Label |",
                "| :--- | :-: | :-: | :-: | :--- |",
            ])
            for m in p.markers:
                lines.append(f"| Marker | {m.marker_id} | {m.position:.3f} s | - | {m.name} |")
            for r in p.regions:
                lines.append(f"| Region | {r.region_id} | {r.start_position:.3f} s | {r.end_position:.3f} s | {r.name} |")

        # Unsupported features & manual adjustments
        lines.extend([
            "",
            "---",
            "",
            "## 5. Compatibility Analysis & Manual Adjustment Guide",
            "",
        ])

        if p.unsupported_features or p.warnings:
            lines.append("### Detected Architectural Differences:")
            for item in p.unsupported_features + p.warnings:
                lines.append(f"- **Note:** {item}")
            lines.append("")

        lines.extend([
            "### Recommended REAPER Configuration Steps:",
            "",
            "1. **Load Realtime FX Chains:**",
            "   - Open REAPER and load the generated project `session.rpp`.",
            "   - Open the **Actions List** (`?` or `Alt+A`).",
            "   - Click **New Action -> Load ReaScript...** and select `session_load_fx.lua`.",
            "   - Click **Run** to instantiate third-party VSTs and Cockos ReaPlugins with the translated parameters.",
            "",
            "2. **Sidechain Ducking Setup (if applicable):**",
            "   - In Audacity, ducking is typically baked destructive processing or set via Auto Duck.",
            "   - In REAPER, configure dynamic sidechain ducking non-destructively:",
            "     1. On the music or background track, open `ReaComp`.",
            "     2. Change track channel count from `2` to `4` (Track Routing window).",
            "     3. Drag a route send from the dialogue/voice track to the music track.",
            "     4. In the send window, set Audio send from `1/2` to channels `3/4`.",
            "     5. In ReaComp on the music track, set **Detector Input** to `Auxiliary Input L+R (3/4)`.",
            "",
            "3. **Non-Destructive Envelope Curves:**",
            "   - If Audacity Envelope Tool control points were present, fade-in and fade-out bounds were mapped directly to REAPER item fades.",
            "   - For continuous volume automation curves across multiple clips, consider inserting a REAPER Volume Envelope (`V`).",
            "",
            "4. **Track Folder / Stem Routing:**",
            "   - In REAPER, any track can act as a bus/folder. Click the folder icon on parent tracks to nest stems logically.",
            "",
            "---",
            "*Report generated by aup3-to-reaper.*",
        ])

        return "\n".join(lines) + "\n"

    def write(self, extraction_summary: Dict[str, Any], filename: Optional[str] = None) -> Path:
        """Write report to session_MIGRATION_REPORT.md."""
        fname = filename or f"{self.project.name}_MIGRATION_REPORT.md"
        report_path = self.output_dir / fname
        content = self.generate(extraction_summary)
        with open(report_path, "w", encoding="utf-8") as f:
            f.write(content)
        logger.info("Generated migration report: %s", report_path)
        return report_path
